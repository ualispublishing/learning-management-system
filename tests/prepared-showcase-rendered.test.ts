test('the shared course mapper preserves omitted settings and never manufactures review approval', async () => {
  const syllabus = JSON.parse(await readFile('demo/ai/results/syllabus.json', 'utf8')) as SyllabusExtraction;
  const original = { title: 'Existing course', description: 'Original', termStart: 100, termEnd: 200, gradingWeights: { Coursework: 40, Exams: 60 } };
  const mapped = mapSyllabusToCourse(syllabus, original);
  assert.equal(mapped.courseFields.title, syllabus.title);
  assert.equal(mapped.courseFields.termStart, original.termStart);
  assert.equal(mapped.courseFields.termEnd, original.termEnd);
  assert.deepEqual(mapped.courseFields.gradingWeights, original.gradingWeights);
  assert.equal('humanReviewedAt' in mapped.syllabusDetails, false);
  assert.equal(original.title, 'Existing course');
  const dated = mapSyllabusToCourse({ ...syllabus, termStart: '2027-01-01', termEnd: '2027-05-01' }, original);
  assert.equal(dated.courseFields.termStart, Date.parse('2027-01-01T00:00:00Z'));
  assert.equal(dated.courseFields.termEnd, Date.parse('2027-05-01T23:59:59Z'));
});

