test('syllabus exports save the visible draft, evidence and safe course mapping; copying has a fallback', async () => {
  ui.render(React.createElement(PreparedAIShowcase));
  await ui.screen.findByRole('button', { name: 'Syllabus' });
  ui.fireEvent.click(ui.screen.getByRole('button', { name: 'Show prepared result' }));
  await ui.screen.findByLabelText('Course information preview');
  for (const label of ['Export syllabus draft', 'Export course mapping', 'Export result JSON']) {
    ui.fireEvent.click(ui.screen.getByRole('button', { name: label }));
    const response = await actualFetch(ui.screen.getByRole('link', { name: 'Save file' }).getAttribute('href')!);
    assert.equal(response.status, 200);
    const contents = await response.text();
    assert.equal(contents, (ui.screen.getByLabelText('Export contents') as HTMLTextAreaElement).value);
    assert.match(contents, /CC BY-NC-SA 4.0/);
    assert.match(contents, /gpt-6-astra/);
    assert.match(contents, /xhigh/);
    if (label === 'Export course mapping') {
      const data = JSON.parse(contents);
      assert.equal(data.humanReview, 'pending');
      assert.equal(data.courseFields.termStart, undefined);
      assert.equal(data.courseFields.termEnd, undefined);
      assert.equal(data.courseFields.gradingWeights, undefined);
      assert.equal(data.syllabusDetails.evidence.length, 36);
      assert.equal(data.syllabusDetails.provenance.preparedGeneration.model, 'gpt-6-astra');
    }
  }
  const originalClipboard = Object.getOwnPropertyDescriptor(navigator, 'clipboard');
  try {
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Denied'); } } });
    ui.fireEvent.click(ui.screen.getByRole('button', { name: 'Copy export text' }));
    await ui.screen.findByText(/Copy is unavailable here/);
    assert.ok(ui.screen.getByLabelText('Export contents'));
    let copied = '';
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (text: string) => { copied = text; } } });
    ui.fireEvent.click(ui.screen.getByRole('button', { name: 'Copy export text' }));
    await ui.screen.findByText('Copied export text.');
    assert.equal(copied, (ui.screen.getByLabelText('Export contents') as HTMLTextAreaElement).value);
  } finally {
    if (originalClipboard) Object.defineProperty(navigator, 'clipboard', originalClipboard);
    else Reflect.deleteProperty(navigator, 'clipboard');
  }
  ui.fireEvent.click(ui.screen.getByRole('button', { name: 'Reset this example' }));
  assert.equal(ui.screen.queryByLabelText('Export preview') === null, true);
  assert.equal(requests.filter(request => request.method !== 'GET').length, 1, 'exporting does not create or publish a course');
});

