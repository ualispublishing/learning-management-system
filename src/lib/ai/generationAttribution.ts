import type { PreparedAIGeneration } from './types.ts';

export function preparedGenerationAttribution(generation?: Omit<PreparedAIGeneration, 'recordSha256'>): string {
  const author = generation?.authoringTool || 'an unrecorded authoring tool';
  const date = generation?.preparedOn ? ` on ${generation.preparedOn}` : '';
  const reasoning = generation?.reasoningEffort ? ` Reasoning: ${generation.reasoningEffort}.` : '';
  const context = generation?.contextMode === 'isolated-agent' ? ' Generated by an isolated agent without inherited conversation history.' : '';
  const enrichment = generation?.enrichmentNote ? ` ${generation.enrichmentNote}` : '';
  return `Prepared with ${author}${date}. Generating model: ${generation?.model || 'not recorded'}.${reasoning}${context}${enrichment} This demo replays saved results; no live AI call is made. Live model outputs may differ.`;
}

const boundedText = (value: unknown, limit: number): value is string => typeof value === 'string'
  && value.trim().length > 0 && value.length <= limit && !/[\u0000-\u001f\u007f\u202a-\u202e\u2066-\u2069]/.test(value);

/** Validates service metadata, never model-generated task JSON. Produces a canonical copy. */
export function readPreparedGeneration(value: unknown): PreparedAIGeneration | undefined {
  if (value === undefined) return undefined;
  const invalid = () => new Error('provenance.preparedGeneration must contain a bounded, recorded authoring attribution.');
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw invalid();
  const record = value as Record<string, unknown>;
  const allowed = ['authoringTool', 'preparedOn', 'model', 'reasoningEffort', 'contextMode', 'enrichmentNote', 'recordSha256'];
  if (Object.keys(record).some(key => !allowed.includes(key))
    || !boundedText(record.authoringTool, 160)
    || typeof record.preparedOn !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(record.preparedOn)
    || !Number.isFinite(Date.parse(record.preparedOn)) || new Date(record.preparedOn).toISOString().slice(0, 10) !== record.preparedOn
    || (record.model !== null && !boundedText(record.model, 160))
    || (record.reasoningEffort !== undefined && !boundedText(record.reasoningEffort, 80))
    || (record.contextMode !== undefined && record.contextMode !== 'isolated-agent')
    || (record.enrichmentNote !== undefined && !boundedText(record.enrichmentNote, 1000))
    || typeof record.recordSha256 !== 'string' || !/^[a-f0-9]{64}$/.test(record.recordSha256)) throw invalid();
  return {
    authoringTool: record.authoringTool, preparedOn: record.preparedOn, model: record.model as string | null,
    ...(record.reasoningEffort !== undefined ? { reasoningEffort: record.reasoningEffort as string } : {}),
    ...(record.contextMode !== undefined ? { contextMode: 'isolated-agent' as const } : {}),
    ...(record.enrichmentNote !== undefined ? { enrichmentNote: record.enrichmentNote as string } : {}),
    recordSha256: record.recordSha256,
  };
}

/** Saved records may predate the current prompt version. Render bounded labels without re-validating old task data. */
export function generationAttribution(provenance: unknown): string | null {
  if (provenance === undefined || provenance === null) return null;
  const unavailable = 'AI generation attribution is unavailable. Ask your administrator to inspect the generation record.';
  if (typeof provenance !== 'object' || Array.isArray(provenance)) return unavailable;
  const record = provenance as Record<string, unknown>;
  if (record.model !== undefined && !boundedText(record.model, 160)) return unavailable;
  try {
    const prepared = readPreparedGeneration(record.preparedGeneration);
    if (prepared && (record.model !== 'prepared-demo/v1' || typeof record.documentSha256 !== 'string' || !/^[a-f0-9]{64}$/i.test(record.documentSha256))) return unavailable;
    if (record.model === 'prepared-demo/v1') return `${preparedGenerationAttribution(prepared)} Replay engine: prepared-demo/v1.`;
    return record.model ? `AI model / adapter reported by the service: ${record.model}.` : 'Generating model: not recorded.';
  } catch { return unavailable; }
}

export function attributionSourceName(value: unknown): string | undefined {
  return boundedText(value, 1024) ? value : undefined;
}
