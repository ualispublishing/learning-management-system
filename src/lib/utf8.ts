/**
 * Returns the number of bytes required to encode a JavaScript string as UTF-8.
 * This intentionally avoids the optional TextEncoder global so the same size
 * limits work in browsers, Hermes, tests, and institution-supplied runtimes.
 */
export function utf8ByteLength(value: string): number {
  let bytes = 0;
  for (let index = 0; index < value.length; index += 1) {
    const codePoint = value.codePointAt(index)!;
    if (codePoint <= 0x7f) bytes += 1;
    else if (codePoint <= 0x7ff) bytes += 2;
    else if (codePoint <= 0xffff) bytes += 3;
    else {
      bytes += 4;
      index += 1;
    }
  }
  return bytes;
}
